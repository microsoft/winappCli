    public PlainPage() => InitializeComponent();
}

public sealed partial class ResourcePage : Page
{
    public ResourcePage() => InitializeComponent();
}

public sealed partial class StyledPage : Page
{
    public StyledPage() => InitializeComponent();
}

public sealed partial class ButtonPage : Page
{
    public ButtonPage() => InitializeComponent();
}

public sealed partial class CheckBoxPage : Page
{
    public CheckBoxPage() => InitializeComponent();
}

public sealed partial class BigTreePage : Page
{
    public BigTreePage() => InitializeComponent();

    protected override void OnNavigatedTo(NavigationEventArgs e)
    {
        var count = e.Parameter is int n ? n : 1000;
        Items.ItemsSource = Enumerable.Range(0, count).Select(i => new BenchRow(i)).ToList();
    }
}
