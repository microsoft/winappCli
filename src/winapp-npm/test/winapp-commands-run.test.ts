import type { PerfStartOptions, PerfMarkOptions } from '../src/winapp-commands';

// The programmatic wrappers in src/winapp-commands.ts are AUTO-GENERATED by
// scripts/generate-commands.mjs. These tests capture the argv the generated
// `run` wrapper actually spawns, so a generator change cannot silently break the
// shipped TypeScript API — in particular the repeatable `--property` emission and
// the position of global flags relative to the `--` passthrough separator.

/**
 * Replace child_process.spawn with a fake that records the argv it is handed and
 * immediately resolves with a success exit code. winapp-cli-utils reads spawn off
 * the shared builtin module at call time, so mutating it here is observed by run().
 */
function captureSpawnArgs(exitCode = 0, stdout = '', stderr = ''): { calls: string[][] } {
  const state = { calls: [] as string[][] };
  mock.method(childProcess, 'spawn', ((_cmd: string, args: string[]) => {
    state.calls.push(args);
    const child = new EventEmitter() as EventEmitter & {
      stdout: EventEmitter;
      stderr: EventEmitter;
    };
    child.stdout = new EventEmitter();
    child.stderr = new EventEmitter();
    // Emit close after listeners are attached (spawn returns synchronously first).
    process.nextTick(() => {
      child.stdout.emit('data', Buffer.from(stdout));
      child.stderr.emit('data', Buffer.from(stderr));
      child.emit('close', exitCode);
    });
    return child;
  }) as unknown as typeof childProcess.spawn);
  return state;
}

afterEach(() => {
  mock.restoreAll();
});

test('generated perf inputs retain the native required-option contract', () => {
  const requiresApp: {} extends Pick<PerfStartOptions, 'app'> ? false : true = true;
  const requiresOutput: {} extends Pick<PerfStartOptions, 'output'> ? false : true = true;
  const requiresMarker: {} extends Pick<PerfMarkOptions, 'name'> ? false : true = true;
  assert.deepEqual([requiresApp, requiresOutput, requiresMarker], [true, true, true]);
});

test('profile settings reach winapp before app arguments and preserve detached JSON readiness', async () => {
  const ready = '{"ProcessId":1234,"Profile":{"CaptureId":"capture","State":"recording"}}';
  const state = captureSpawnArgs(0, ready);
  const result = await run({
    input: '.',
    profile: 'trace folder',
    profileDurationSec: 12,
    profileMaxSizeMib: 64,
    detach: true,
    json: true,
    appArgs: ['--profile', 'app-value'],
  });
  const args = state.calls[0];
  const separator = args.indexOf('--');
  assert.deepEqual(args.slice(separator + 1), ['--profile', 'app-value']);
  assert.ok(args.indexOf('--profile') < separator);
  assert.equal(args[args.indexOf('--profile') + 1], 'trace folder');
  assert.equal(args[args.indexOf('--profile-duration-sec') + 1], '12');
  assert.equal(args[args.indexOf('--profile-max-size-mib') + 1], '64');
  assert.equal(result.stdout, ready);
});

test('perf lifecycle wrappers forward capture identity and marker names', async () => {
  const state = captureSpawnArgs();
  await perfStart({ app: '1234', output: 'trace folder', durationSec: 12, maxSizeMib: 64, json: true });
  await perfStatus({ captureId: 'capture', json: true });
  await perfMark({ captureId: 'capture', name: 'scroll-start', json: true });
  await perfStop({ captureId: 'capture', json: true });
  assert.deepEqual(state.calls[0].slice(0, 2), ['perf', 'start']);
  assert.equal(state.calls[0][state.calls[0].indexOf('--app') + 1], '1234');
  assert.equal(state.calls[0].includes('--pid'), false);
  assert.equal(state.calls[0][state.calls[0].indexOf('--output') + 1], 'trace folder');
  assert.deepEqual(state.calls[1], ['perf', 'status', '--json', '--', 'capture']);
  assert.deepEqual(state.calls[2], ['perf', 'mark', '--json', '--name', 'scroll-start', '--', 'capture']);
  assert.deepEqual(state.calls[3], ['perf', 'stop', '--json', '--', 'capture']);
});

test('perf start preserves process names and window titles as one app argument', async () => {
  const state = captureSpawnArgs();
  const selectors = ['WinUIBenchmarkApp', 'Benchmark', 'WinUI Performance Lab'];
  for (const app of selectors) {
    await perfStart({ app, output: 'trace folder', json: true });
  }
  assert.deepEqual(
    state.calls.map((args) => args[args.indexOf('--app') + 1]),
    selectors
  );
});

test('partial perf queries reject without discarding bounded evidence on stdout', async () => {
  const evidence = '{"rows":[{"id":"e1"}],"coverage":{"complete":false}}';
  const failure = '{"code":"partial_data","partialOutput":true}';
  const state = captureSpawnArgs(1, evidence, failure);
  await assert.rejects(
    perfAnalyze({
      directory: 'trace',
      fromMarker: 'scroll-start',
      toMarker: 'scroll-end',
      view: 'elements',
      limit: 10,
      maxBytes: 4096,
      json: true,
    }),
    (error: unknown) => {
      assert.ok(error instanceof Error && 'stdout' in error && 'stderr' in error && 'exitCode' in error);
      assert.equal(error.stdout, evidence);
      assert.equal(error.stderr, failure);
      assert.equal(error.exitCode, 1);
      return true;
    }
  );
  assert.deepEqual(state.calls[0].slice(0, 2), ['perf', 'analyze']);
  assert.equal(state.calls[0][state.calls[0].indexOf('--') + 1], 'trace');
  assert.equal(state.calls[0][state.calls[0].indexOf('--from-marker') + 1], 'scroll-start');
});

test('operation trees and GC queries preserve bounded analysis arguments', async () => {
  const state = captureSpawnArgs();
  await perfAnalyze({ directory: 'trace', view: 'calls', family: 'layout', json: true });
  await perfAnalyze({ directory: 'trace', view: 'call', id: 'c42', depth: 3, offset: 2, maxBytes: 4096, json: true });
  await perfAnalyze({ directory: 'trace', view: 'gc', fromMs: 500, toMs: 1500, json: true });
  for (const [index, view] of ['calls', 'call', 'gc'].entries()) {
    assert.equal(state.calls[index][state.calls[index].indexOf('--view') + 1], view);
  }
  assert.equal(state.calls[0][state.calls[0].indexOf('--family') + 1], 'layout');
  assert.equal(state.calls[1][state.calls[1].indexOf('--id') + 1], 'c42');
  assert.equal(state.calls[1][state.calls[1].indexOf('--depth') + 1], '3');
  assert.equal(state.calls[1][state.calls[1].indexOf('--max-bytes') + 1], '4096');
  assert.equal(state.calls[2][state.calls[2].indexOf('--from-ms') + 1], '500');
});

