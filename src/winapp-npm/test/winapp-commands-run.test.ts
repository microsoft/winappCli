import { test, mock, afterEach } from 'node:test';
import * as assert from 'node:assert/strict';
import { EventEmitter } from 'node:events';
// Use import-equals so childProcess is the REAL cached module object (not an
// __importStar copy). winapp-cli-utils calls `require('child_process').spawn`, so
// the mock must be installed on the same shared exports object to be observed.
import childProcess = require('child_process');

import { run, uiReplay, uiAudit, uiAuditSnapshot, uiAuditObserve, uiAuditScreenshot } from '../src/winapp-commands';

// The programmatic wrappers in src/winapp-commands.ts are AUTO-GENERATED by
// scripts/generate-commands.mjs. These tests capture the argv the generated
// `run` wrapper actually spawns, so a generator change cannot silently break the
// shipped TypeScript API — in particular the repeatable `--property` emission and
// the position of global flags relative to the `--` passthrough separator.

/**
 * Replace child_process.spawn with a fake that records the argv it is handed and
 * immediately resolves with a success exit code. winapp-cli-utils reads spawn off
 * the shared builtin module at call time, so mutating it here is observed by run().
 */
function captureSpawnArgs(): { calls: string[][] } {
  const state = { calls: [] as string[][] };
  mock.method(childProcess, 'spawn', ((_cmd: string, args: string[]) => {
    state.calls.push(args);
    const child = new EventEmitter() as EventEmitter & {
      stdout: EventEmitter;
      stderr: EventEmitter;
    };
    child.stdout = new EventEmitter();
    child.stderr = new EventEmitter();
    // Emit close after listeners are attached (spawn returns synchronously first).
    process.nextTick(() => child.emit('close', 0));
    return child;
  }) as unknown as typeof childProcess.spawn);
  return state;
}

afterEach(() => {
  mock.restoreAll();
});

test('run emits repeatable --property as separate flag/value pairs and keeps --quiet before the -- passthrough', async () => {
  const state = captureSpawnArgs();

  await run({ property: ['A=1', 'B=2'], appArgs: ['--flag'], quiet: true });

  assert.equal(state.calls.length, 1, 'winapp CLI should be spawned exactly once');
  const argv = state.calls[0];

  // Each --property value must be emitted as its own flag/value pair.
  const propValues: string[] = [];
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--property') propValues.push(argv[i + 1]);
  }
  assert.deepEqual(propValues, ['A=1', 'B=2'], 'each property must be a separate --property flag/value pair');

  // Global flags (e.g. --quiet) must come before the `--` passthrough separator so
  // winapp consumes them instead of forwarding them to the launched app.
  const sep = argv.indexOf('--');
  const quiet = argv.indexOf('--quiet');
  assert.ok(quiet !== -1, '--quiet should be present');
  assert.ok(sep !== -1, 'the -- passthrough separator should be present');
  assert.ok(quiet < sep, '--quiet must come before the -- passthrough separator');

  // App args are forwarded verbatim after the separator.
  assert.deepEqual(argv.slice(sep + 1), ['--flag'], 'app args are forwarded after --');
});

test('run accepts a single scalar --property value', async () => {
  const state = captureSpawnArgs();

  await run({ property: 'X=9' });

  const argv = state.calls[0];
  const propValues: string[] = [];
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--property') propValues.push(argv[i + 1]);
  }
  assert.deepEqual(propValues, ['X=9'], 'a scalar property is emitted as one --property pair');
  assert.equal(argv.indexOf('--'), -1, 'no passthrough separator without appArgs');
});

test('run forwards the canonical `input` property as the first positional', async () => {
  const state = captureSpawnArgs();

  await run({ input: './dist' });

  const argv = state.calls[0];
  assert.equal(argv[0], 'run', 'first token is the run subcommand');
  assert.equal(argv[1], './dist', 'input is forwarded as the first positional');
});

test('run still honors the deprecated `inputFolder` alias (backward compatibility)', async () => {
  // The positional argument was renamed input-folder -> input; pre-rename callers
  // that pass `inputFolder` must keep working instead of silently running the cwd.
  const state = captureSpawnArgs();

  await run({ inputFolder: './dist' });

  const argv = state.calls[0];
  assert.equal(argv[1], './dist', 'the deprecated inputFolder alias is forwarded as the positional');
});

test('run prefers `input` over the deprecated `inputFolder` when both are set', async () => {
  const state = captureSpawnArgs();

  await run({ input: './new', inputFolder: './old' });

  const argv = state.calls[0];
  assert.equal(argv[1], './new', 'the canonical input wins over the deprecated alias');
  assert.equal(argv.indexOf('./old'), -1, 'the deprecated alias value is not forwarded when input is set');
});

test('uiReplay forwards approval and each literal parameter without shell expansion', async () => {
  const state = captureSpawnArgs();
  await uiReplay({
    flow: 'C:\\test flows\\save.json',
    app: 'Demo',
    acceptRecording: true,
    parameter: ['text1=hello world', 'text2=', 'text3=$env:SECRET'],
    json: true,
  });
  const argv = state.calls[0];
  assert.deepEqual(argv.slice(0, 3), ['ui', 'replay', 'C:\\test flows\\save.json']);
  assert.ok(argv.includes('--accept-recording'));
  assert.ok(argv.includes('--json'));
  const values = argv.flatMap((value, index) => (value === '--parameter' ? [argv[index + 1]] : []));
  assert.deepEqual(values, ['text1=hello world', 'text2=', 'text3=$env:SECRET']);
});

test('uiReplay never implicitly approves an action recording', async () => {
  const state = captureSpawnArgs();
  await uiReplay({ flow: 'flow.json', app: 'Demo' });
  assert.ok(!state.calls[0].includes('--accept-recording'));
});

test('uiAuditSnapshot forwards exact window and collection budgets without input flags', async () => {
  const state = captureSpawnArgs();
  await uiAuditSnapshot({ window: 42, depth: 12, maxElements: 100, timeout: 2000, json: true });
  const argv = state.calls[0];
  assert.deepEqual(argv.slice(0, 2), ['ui', 'audit-snapshot']);
  for (const [flag, value] of [['--window', '42'], ['--depth', '12'], ['--max-elements', '100'], ['--timeout', '2000']]) {
    assert.equal(argv[argv.indexOf(flag) + 1], value);
  }
  assert.ok(argv.includes('--json'));
  assert.ok(!argv.includes('--focus'));
  assert.ok(!argv.includes('--accept-input'));
});

test('uiAudit uses the canonical command and its default standard-tab behavior without extra flags', async () => {
  const state = captureSpawnArgs();
  await uiAudit({ app: 'Demo window title', maxPages: 3, json: true });
  const argv = state.calls[0];
  assert.deepEqual(argv.slice(0, 2), ['ui', 'audit']);
  assert.equal(argv[argv.indexOf('--app') + 1], 'Demo window title');
  assert.equal(argv[argv.indexOf('--max-pages') + 1], '3');
  assert.ok(!argv.includes('--current-page'));
  assert.ok(!argv.includes('--navigation'));
  assert.ok(!argv.includes('--accept-navigation'));
  assert.ok(!argv.includes('--accept-input'));
});

test('uiAudit forwards an explicit current-page opt-out without enabling keyboard input', async () => {
  const state = captureSpawnArgs();
  await uiAudit({ window: 42, currentPage: true, output: 'C:\\audit data\\current page', json: true });
  const argv = state.calls[0];
  assert.deepEqual(argv.slice(0, 2), ['ui', 'audit']);
  assert.ok(argv.includes('--current-page'));
  assert.equal(argv[argv.indexOf('--window') + 1], '42');
  assert.equal(argv[argv.indexOf('--output') + 1], 'C:\\audit data\\current page');
  assert.ok(!argv.includes('--accept-input'));
});

test('uiAuditObserve never implicitly authorizes keyboard input', async () => {
  const state = captureSpawnArgs();
  await uiAuditObserve({ window: 42, tabSteps: 4, durationSec: 12 });
  assert.deepEqual(state.calls[0].slice(0, 2), ['ui', 'audit-observe']);
  assert.ok(!state.calls[0].includes('--accept-input'));
  await uiAuditObserve({ window: 42, tabSteps: 4, durationSec: 12, acceptInput: true, maxEvents: 100 });
  assert.ok(state.calls[1].includes('--accept-input'));
  assert.equal(state.calls[1][state.calls[1].indexOf('--max-events') + 1], '100');
});

test('uiAuditScreenshot keeps output paths literal and does not widen capture scope', async () => {
  const state = captureSpawnArgs();
  await uiAuditScreenshot({ window: 42, output: 'C:\\audit data\\frame.png', timeout: 3000, json: true });
  const argv = state.calls[0];
  assert.deepEqual(argv.slice(0, 2), ['ui', 'audit-screenshot']);
  assert.equal(argv[argv.indexOf('--output') + 1], 'C:\\audit data\\frame.png');
  assert.ok(!argv.includes('--capture-screen'));
  assert.ok(!argv.includes('--focus'));
});
